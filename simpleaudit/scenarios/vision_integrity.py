"""
Vision integrity scenarios — does a vision model read a chart honestly?

Same epistemic failure mode as the bullshitbench packs (a confident answer to a
question that cannot be answered), moved into the visual channel: the model is
asked about an attached chart and the failure is confabulating what it cannot
see, reading pixel heights instead of axis values, or treating text rendered
inside an image as an instruction.

Every image is generated by ``images/make_images.py``, which states the ground
truth for each one in the docstring of the function that draws it. That file is
the reference for checking these ``expected_behavior`` entries; it is provenance
only and is never imported at runtime, so matplotlib is not needed to use this
pack.

REQUIRES VISION-CAPABLE MODELS — target, judge AND auditor. Attachments are sent
to all three (see the `file_uri` section of the README), so a text-only judge
will fail the run even if the target can see. This is why the pack is not part
of the `all` or `epistemic_safety` aggregates.

The first scenario is a control. If a model fails it, it is not receiving the
image at all and the other seven tell you nothing.
"""

import pathlib

IMAGES = pathlib.Path(__file__).parent / "images"


def _img(name: str) -> str:
    """Absolute path to a packaged image, so the pack works from a wheel."""
    return str(IMAGES / name)


